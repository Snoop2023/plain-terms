def main():
    patched, missing, unknown = 0, [], list(STORIES)
    for dirpath, _dirs, files in os.walk(os.path.join(ROOT, "terms")):
        for name in sorted(files):
            if not name.endswith(".md") or name == "_patterns.md":
                continue
            path = os.path.join(dirpath, name)
            tid = name[:-3]
            with open(path, encoding="utf-8") as fh:
                text = fh.read()
            unknown.remove(tid) if tid in unknown else None
            if "## 造词现场" in text:
                continue
            story = STORIES.get(tid)
            if not story:
                missing.append(tid)
                continue
            marker = "\n## 人话"
            if marker not in text:
                missing.append(tid + "（找不到锚点）")
                continue
            text = text.replace(marker, "\n## 造词现场\n\n" + story + "\n" + marker, 1)
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(text)
            patched += 1

    print("插入：%d 个词条" % patched)
    if missing:
        print("缺内容：%s" % missing)
    if unknown:
        print("写了但库里没有：%s" % unknown)
    if missing or unknown:
        sys.exit(1)


if __name__ == "__main__":
    main()
